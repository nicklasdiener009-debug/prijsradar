const KEY = 'ams-lang-v1';
let current = 'en';
try {
  const saved = localStorage.getItem(KEY);
  current = saved === 'nl' || saved === 'en' ? saved : (navigator.language || '').toLowerCase().startsWith('nl') ? 'nl' : 'en';
} catch { /* default */ }

export const lang = () => current;
export const locale = () => (current === 'nl' ? 'nl-NL' : 'en-GB');
export function setLang(l) {
  current = l === 'nl' ? 'nl' : 'en';
  try { localStorage.setItem(KEY, current); } catch { /* ignore */ }
}
export function t(en, vars) {
  let s = current === 'nl' ? NL[en] ?? en : en;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
  return s;
}
export const hasDutch = (en) => en in NL;
